const fs = require("node:fs");
const path = require("node:path");

// Inquiry and landing are independent public pages, not Flutter build outputs.
const entrypoints = ["index.html"];

function appEntryHtml(root) {
  const source = fs.readFileSync(path.join(root, "app/index.html"), "utf8");
  const migration = fs.readFileSync(path.join(root, "lib/app-entry-referral.js"), "utf8");
  const bootstrap = '  <script src="flutter_bootstrap.js';
  if (!source.includes('<base href="/app/">') || source.split(bootstrap).length !== 2) {
    throw new Error("Unexpected app entry format; review the shared app base before publishing");
  }
  return source.replace("<html>", '<html lang="ko">').replace(bootstrap,
    `  <!-- Generated by tools/sync-app-entrypoints.cjs from app/index.html. -->\n  <script data-recar-entry-migration>\n${migration}  </script>\n${bootstrap}`);
}

function syncAppEntrypoints(root = path.resolve(__dirname, ".."), { check = false } = {}) {
  const html = appEntryHtml(root);
  for (const entry of entrypoints) {
    const target = path.join(root, entry);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== html) {
        throw new Error(`${entry} differs from the published app; run npm run sync:app-entries`);
      }
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, html);
    }
  }
  return entrypoints;
}

if (require.main === module) {
  syncAppEntrypoints(undefined, { check: process.argv.includes("--check") });
}

module.exports = { appEntryHtml, syncAppEntrypoints, entrypoints };
